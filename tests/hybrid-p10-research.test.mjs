import assert from 'node:assert/strict';
import {createResearchSession,summarizeResearch} from '../src/beta-research.mjs';
let now=0;const a=createResearchSession({clock:()=>now,consent:false});
assert.equal(a.record('session-start'),false);
assert.throws(()=>a.export(),/opt-in/);
a.consent(true);assert.equal(a.record('session-start'),true);
now+=1800;a.record('preview-ready',{task:'preview'});
assert.throws(()=>a.record('preview-ready',{userEmail:'a@example.org'}),/allowlisted/);
assert.throws(()=>a.record('preview-ready',{task:'collect-payment'}),/Unknown study task/);
a.record('scrub-success',{task:'scrub'});
a.respond({outcome:'complete',monthlyPrice:'12',ease:4,quality:4,
 blocker:'The character library was harder to find than expected.'});
const report=a.export();
assert.equal(report.schema,'frameforge.beta-study/1');
assert.equal(report.events.length,3);
assert.equal(report.events[1].ms,1800);
assert.equal(summarizeResearch([report]).taskCompletionRate,1);
assert.equal(summarizeResearch([]).taskCompletionRate,null);
assert.equal(summarizeResearch([report]).actualPaidCustomers,0);
const b=createResearchSession({consent:true});
b.respond({outcome:'blocked',monthlyPrice:'none',ease:1,quality:2,blocker:'Could not export'});
const combined=summarizeResearch([report,b.export()]);
assert.equal(combined.participants,2);assert.equal(combined.outcome.blocked,1);
assert.equal(combined.willingness['12'],1);
assert.match(combined.recommendation,/Not enough/);
assert.throws(()=>b.respond({outcome:'complete',monthlyPrice:'999',ease:7,quality:3}),/Incomplete/);
a.consent(false);assert.equal(a.record('session-start'),false);
a.consent(true);assert.equal(a.export().events.length,0,'revoking consent clears prior session data');
console.log('HYBRID_P10_RESEARCH_PASS: explicit consent, privacy field allowlist, local deletion, no fake buyer conversions');