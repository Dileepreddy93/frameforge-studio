'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const core=require('../src/hybrid-project-core.js'),ed=require('../src/hybrid-editor-core.js');
const legacy=JSON.parse(fs.readFileSync('projects/zero-latency.frameforge.json','utf8'));
const p=ed.fromLegacy(legacy),state=ed.createEditor(p);
assert.equal(core.validateProject(p).valid,true);
assert.equal(p.hybrid.world.template,'forest');
assert.equal(state.canUndo,false);
assert.equal(state.voiced,false);
assert.equal(state.cast('luna',{template:'creator',voice:'af_bella',name:'Nova'}),true);
assert.equal(state.project.characters[0].name,'Nova');
assert.equal(state.cast('luna',{look:{top:'#258ba6',accent:'#e1bf83',hairStyle:'bun'},style:'lowpoly'}),true);
assert.deepEqual(state.project.hybrid.cast.luna.look,{top:'#258ba6',accent:'#e1bf83',hairStyle:'bun'});
assert.equal(state.project.hybrid.cast.luna.style,'lowpoly');
assert.throws(()=>state.cast('luna',{look:{top:'red'}}),/RRGGBB/);
assert.throws(()=>state.cast('luna',{look:{head:100}}),/supported range/);
assert.throws(()=>state.cast('luna',{look:{unknown:'yes'}}),/Unknown appearance field/);

assert.equal(state.shot('shot-01',{dialogue:'We are creating a new original movie.'}),true);
assert.equal(state.shot('shot-01',{emotion:'surprised',action:'wave',move:'push'}),true);
const propEditor=ed.createEditor(p);
assert.equal(propEditor.shot('shot-01',{visualProp:'lantern'}),true);
assert.equal(propEditor.project.shots[0].visualProp,'lantern');
assert.equal(ed.parseCreatorFile(propEditor.serialize()).shots[0].visualProp,'lantern');
assert.equal(propEditor.shot('shot-01',{propMode:'reach',propActor:'luna',camera:'prop'}),true);
assert.deepEqual(propEditor.project.shots[0].propInteraction,{mode:'reach',actor:'luna'});
assert.equal(propEditor.project.shots[0].camera.kind,'prop');
assert.deepEqual(ed.parseCreatorFile(propEditor.serialize()).shots[0].propInteraction,{mode:'reach',actor:'luna'});
assert.throws(()=>propEditor.shot('shot-01',{propMode:'teleport'}),/Unsupported prop interaction/);
assert.throws(()=>propEditor.shot('shot-01',{propActor:'missing'}),/Unknown actor/);
const propScript=propEditor.scriptText();
assert.match(propScript,/@prop name=lantern/);
assert.equal(ed.createEditor(propEditor.project).script(propScript),false);
assert.throws(()=>propEditor.shot('shot-01',{visualProp:'unlicensed-model'}),/Unsupported original 3D prop/);
const unsafe=structuredClone(propEditor.project);unsafe.shots[0].visualProp='unsafe';
assert.throws(()=>ed.parseCreatorFile(JSON.stringify(unsafe)),/Invalid hybrid project/);
assert.equal(propEditor.shot('shot-01',{visualProp:'none'}),true);
assert.equal(propEditor.project.shots[0].visualProp,undefined);
assert.equal(propEditor.project.shots[0].propInteraction,undefined);
assert.equal(propEditor.project.shots[0].camera.kind,'actor');

const cameraTest=ed.createEditor(state.project);
assert.equal(cameraTest.shot('shot-01',{cameraDistance:6.2,cameraFov:42}),true);
assert.equal(cameraTest.project.shots[0].framing.distance,6.2);
assert.equal(cameraTest.project.shots[0].framing.fov,42);
assert.throws(()=>cameraTest.shot('shot-01',{cameraDistance:100}),/3–20/);
assert.throws(()=>cameraTest.shot('shot-01',{cameraFov:10}),/25–60/);
cameraTest.shot('shot-01',{speaker:'atlas'});
assert.equal(cameraTest.project.shots[0].camera.target,'atlas','Actor camera follows selected speaker');
cameraTest.shot('shot-01',{camera:'two'});
assert.notEqual(cameraTest.project.shots[0].camera.secondary,'atlas');
assert.equal(cameraTest.project.shots[0].framing,undefined,'Changing shot type resets unrelated custom zoom');

assert.equal(state.world('snow','night'),true);
state.addShot();assert.equal(state.project.shots.length,3);
const last=state.project.shots[2].id;
state.moveShot(last,-1);assert.equal(state.project.shots[1].id,last);
state.shot(last,{screenKind:'terminal',screenTitle:'Local rendering',screenLines:'> build\nDone',caption:'RENDER COMPLETE'});
assert.equal(state.project.shots[1].screen.lines.length,2);
assert.equal(state.project.shots[1].caption,'RENDER COMPLETE');
const snap=state.serialize(),p2=ed.parseCreatorFile(snap);
assert.deepEqual(p2,state.project);
assert.ok(snap.length<1_048_576);
const copy=ed.createEditor(p2);
copy.markVoiced();assert.equal(copy.voiced,true);
copy.shot(last,{dialogue:'The line changed, so regenerate speech.'});
assert.equal(copy.voiced,false,'Cannot export stale synthesized speech after editing dialogue');
copy.undo();assert.equal(copy.voiced,false,'Undo cannot resurrect untracked PCM audio');
state.undo();assert.equal(state.project.shots[1].caption,undefined);
state.redo();assert.equal(state.project.shots[1].caption,'RENDER COMPLETE');
const script=state.scriptText();
const fromScript=ed.createEditor(p2);
assert.equal(fromScript.script(script),false,'No-op roundtrip script is deterministic');
const unknown=structuredClone(p2);unknown.hybrid.cast['luna']={provider:'rigged',assetId:'stolen'};
assert.throws(()=>ed.parseCreatorFile(JSON.stringify(unknown)),/Missing character asset|Invalid hybrid project/);
assert.throws(()=>ed.parseCreatorFile('x'.repeat(1_048_577)),/under 1 MB/);
assert.throws(()=>state.shot(last,{duration:30}),/0.5/);
assert.throws(()=>state.cast('luna',{template:'unsupported'}),/Unsupported/);
assert.throws(()=>state.shot(last,{dialogue:' '.repeat(3)}),/Dialogue/);
assert.equal(core.validateProject(legacy).valid,true);
state.soundtrack('groove');
state.shotSound(last,'whoosh');
assert.equal(state.project.audio.music.cues[0].style,'groove');
assert.deepEqual(state.project.shots[1].sfx,[{cue:'whoosh',at:.2,gain:-12}]);
const scoreProject=ed.parseCreatorFile(state.serialize());
assert.deepEqual(scoreProject.audio.music,state.project.audio.music,'Original score persists in export/import');
assert.deepEqual(scoreProject.shots[1].sfx,state.project.shots[1].sfx,'Shot SFX persist in export/import');
state.markVoiced();assert.equal(state.voiced,true);
state.soundtrack('tension');assert.equal(state.voiced,false,'Changing music requires new mastered audio');
assert.throws(()=>state.soundtrack('external-copyright-song'),/Unsupported soundtrack/);
assert.throws(()=>state.shotSound(last,'unlicensed-clip'),/Unsupported shot sound/);
state.soundtrack('off');state.shotSound(last,'none');
assert.ok(!state.project.audio.music&&state.project.shots[1].sfx===undefined);
console.log('HYBRID_P7_CREATOR_CORE_PASS: fresh v2, edits/undo/redo, save/reopen, voice invalidation, camera/screens and safe import');