'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const core=require('../src/hybrid-project-core.js'),ed=require('../src/hybrid-editor-core.js');
const legacy=JSON.parse(fs.readFileSync('projects/zero-latency.frameforge.json','utf8'));
const p=ed.fromLegacy(legacy),state=ed.createEditor(p);
assert.equal(core.validateProject(p).valid,true);
