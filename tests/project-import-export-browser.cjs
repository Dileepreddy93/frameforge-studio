const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
const base=JSON.parse(fs.readFileSync('projects/mountain-mystery.frameforge.json','utf8'));
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1050,height:840},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.FRAMEFORGE_URL||'http://127.0.0.1:8958/',{waitUntil:'domcontentloaded',timeout:35000});
 await page.waitForFunction(()=>window.FrameForgeProjectsLoaded===true&&FrameForgeQA?.shots().length===14,null,{timeout:35000});
 const project=structuredClone(base);
 project.id='uploaded-story';project.title='Uploaded Story';
 project.shots[0].dialogue='Imported episodes use real project documents.';
 await page.locator('#projectImport').setInputFiles({name:'uploaded-story.frameforge.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
 await page.waitForFunction(()=>window.FrameForgeCurrentProject?.id==='uploaded-story',null,{timeout:16000});
 assert.equal(await page.locator('#preset').inputValue(),'custom');
 assert.equal(await page.locator('#dialogue').inputValue(),project.shots[0].dialogue);
 await page.locator('#dialogue').fill('Edited dialogue must survive download.');
 await page.locator('#apply').click();
 const downloadPromise=page.waitForEvent('download',{timeout:13000});
 await page.locator('#download').click();
 const download=await downloadPromise;
 assert.equal(download.suggestedFilename(),'uploaded-story.frameforge.json');
 const saved=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 assert.equal(saved.shots[0].dialogue,'Edited dialogue must survive download.');
 assert.equal(saved.schema,'frameforge.project/1');
 assert.equal(saved.shots.length,6);
 const unsupported=structuredClone(project);
 unsupported.characters.push({...unsupported.characters[0],id:'alien',name:'ALIEN'});
 unsupported.shots[0].speaker='alien';
 await page.locator('#projectImport').setInputFiles({name:'unsupported.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(unsupported))});
 await page.waitForFunction(()=>document.querySelector('#projectImportStatus')?.textContent.includes('Import rejected:'),null,{timeout:10000});
 assert.equal(await page.evaluate(()=>window.FrameForgeCurrentProject.id),'uploaded-story');
 assert.deepEqual(errors,[]);
 console.log('IMPORT_EDIT_EXPORT_QA_PASS '+JSON.stringify({savedFile:download.suggestedFilename(),scenes:saved.shots.length,editedLine:saved.shots[0].dialogue,rejectsUnknownRigs:true,errors}));
 await browser.close();
})().catch(e=>{console.error('IMPORT_EDIT_EXPORT_QA_FAIL '+e.stack);process.exit(1)});
